"""# Q-Learning implementation"""

q_table = {}
alpha = 0.1
gamma = 0.9
epsilon = 0.1

def get_q_value(state, action):
    state_key = (state['avg_rating'], state['num_rated'])
    return q_table.get((state_key, action), 0.0)

def set_q_value(state, action, value):
    state_key = (state['avg_rating'], state['num_rated'])
    q_table[(state_key, action)] = value

def choose_action(state, available_actions):
    if random.random() < epsilon:
        return random.choice(available_actions)
    else:
        q_values = [get_q_value(state, a) for a in available_actions]
        max_q = max(q_values) if q_values else 0
        max_actions = [a for a, q in zip(available_actions, q_values) if q == max_q]
        return random.choice(max_actions if max_actions else available_actions)  # E

episodes = 200
total_rewards = []
print(f"\nTraining Q-Learning for {episodes} episodes...")
for episode in range(episodes):
    state = env.reset()
    episode_reward = 0
    done = False
    while not done:
        action = choose_action(state, env.available_actions)
        next_state, reward, done = env.step(action)
        episode_reward += reward

        current_q = get_q_value(state, action)
        next_q_values = [get_q_value(next_state, a) for a in env.available_actions]
        max_next_q = max(next_q_values) if next_q_values else 0
        new_q = current_q + alpha * (reward + gamma * max_next_q - current_q)
        set_q_value(state, action, new_q)
        state = next_state
    total_rewards.append(episode_reward)
    if (episode + 1) % 10 == 0:
        print(f"Episode {episode + 1}, Total Reward: {episode_reward}")

q_learning_results = pd.DataFrame({
    'Episode': range(1, episodes + 1),
    'Total_Reward': total_rewards
})
q_learning_results.to_csv('q_learning_results.csv', index=False)
print("\nQ-Learning results saved as 'q_learning_results.csv'.")

